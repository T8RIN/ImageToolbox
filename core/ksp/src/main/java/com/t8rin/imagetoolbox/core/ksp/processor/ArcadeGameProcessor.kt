package com.t8rin.imagetoolbox.core.ksp.processor

import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.processing.Resolver
import com.google.devtools.ksp.processing.SymbolProcessor
import com.google.devtools.ksp.processing.SymbolProcessorEnvironment
import com.google.devtools.ksp.processing.SymbolProcessorProvider
import com.google.devtools.ksp.symbol.ClassKind
import com.google.devtools.ksp.symbol.KSAnnotated
import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.google.devtools.ksp.symbol.KSFile
import com.google.devtools.ksp.symbol.Modifier

internal class ArcadeGameProcessor : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
        object : SymbolProcessor {
            private var generated = false

            override fun process(resolver: Resolver): List<KSAnnotated> {
                if (generated) return emptyList()

                val definition = resolver.getClassDeclarationByName(
                    resolver.getKSNameFromString("$PACKAGE.ArcadeGameDefinition")
                ) ?: return emptyList()
                val source = definition.containingFile ?: return emptyList()
                val type = definition.asStarProjectedType()
                val files = mutableSetOf<KSFile>()
                val names = mutableSetOf("RANDOM", "RANDOMFAVORITE")
                val games = resolver.getSymbolsWithAnnotation("$PACKAGE.RegisterArcadeGame")
                    .filterIsInstance<KSClassDeclaration>()
                    .mapNotNull { declaration ->
                        val file = declaration.containingFile ?: return@mapNotNull null
                        if (declaration.classKind != ClassKind.OBJECT ||
                            Modifier.DATA !in declaration.modifiers ||
                            Modifier.PRIVATE in declaration.modifiers ||
                            declaration.parentDeclaration != null ||
                            !type.isAssignableFrom(declaration.asStarProjectedType())
                        ) {
                            environment.logger.error(
                                "@RegisterArcadeGame requires a visible top-level ArcadeGameDefinition data object",
                                declaration
                            )
                            return@mapNotNull null
                        }
                        if (!files.add(file)) {
                            environment.logger.error(
                                "Declare one arcade game per file",
                                declaration
                            )
                            return@mapNotNull null
                        }

                        val shortName = declaration.simpleName.asString().removeSuffix("Game")
                        val number = shortName.removePrefix("Game")
                        val name =
                            number.takeIf { it.isNotEmpty() && it.all(Char::isDigit) } ?: shortName
                        if (!name.matches(GAME_NAME) || !names.add(name.uppercase())) {
                            environment.logger.error(
                                "Invalid or duplicate arcade game name: $name",
                                declaration
                            )
                            return@mapNotNull null
                        }

                        val reference = requireNotNull(declaration.qualifiedName).asString()
                            .split('.').joinToString(".") { "`$it`" }
                        name to reference
                    }.sortedBy { it.first }.toList()

                environment.codeGenerator.createNewFile(
                    dependencies = Dependencies(true, source, *files.toTypedArray()),
                    packageName = PACKAGE,
                    fileName = "ArcadeGameRegistrations"
                ).bufferedWriter().use { writer ->
                    writer.appendLine("// Generated by KSP — do not edit")
                    writer.appendLine("package $PACKAGE")
                    writer.appendLine()
                    writer.appendLine("internal val registeredArcadeGames: List<ArcadeGame> = listOf(")
                    games.forEach { (name, reference) ->
                        writer.appendLine("    ArcadeGame(\"$name\", $reference),")
                    }
                    writer.appendLine(")")
                }
                generated = true
                return emptyList()
            }
        }

    private companion object {
        const val PACKAGE = "com.t8rin.imagetoolbox.core.games"
        val GAME_NAME = Regex("[A-Za-z0-9]+")
    }
}
