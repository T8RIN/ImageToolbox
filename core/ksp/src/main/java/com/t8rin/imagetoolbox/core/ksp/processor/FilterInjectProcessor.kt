@file:Suppress("unused")

package com.t8rin.imagetoolbox.core.ksp.processor

import com.google.devtools.ksp.processing.Dependencies
import com.google.devtools.ksp.processing.Resolver
import com.google.devtools.ksp.processing.SymbolProcessor
import com.google.devtools.ksp.processing.SymbolProcessorEnvironment
import com.google.devtools.ksp.processing.SymbolProcessorProvider
import com.google.devtools.ksp.symbol.KSAnnotated
import com.google.devtools.ksp.symbol.KSClassDeclaration

internal class FilterInjectProcessor : SymbolProcessorProvider {
    override fun create(
        environment: SymbolProcessorEnvironment
    ): SymbolProcessor = FilterInjectProcessorImpl(environment)
}

private class FilterInjectProcessorImpl(
    environment: SymbolProcessorEnvironment
) : SymbolProcessor {

    private val logger = environment.logger
    private val codegen = environment.codeGenerator

    override fun process(resolver: Resolver): List<KSAnnotated> {
        logger.info("START generation of filter map")
        val annotationFqn = "$PACKAGE.core.ksp.annotations.FilterInject"

        val annotated = resolver.getSymbolsWithAnnotation(annotationFqn)
            .filterIsInstance<KSClassDeclaration>()
            .sortedBy { it.simpleName.asString() }
            .toList()

        if (annotated.isEmpty()) {
            logger.info("No annotated classes found")
            return emptyList()
        }

        val fileName = "FilterMappings"
        val packageName = "$PACKAGE.generated"
        val files = annotated.mapNotNull { it.containingFile }.toTypedArray()

        val file = codegen.createNewFile(
            dependencies = Dependencies(false, *files),
            packageName = packageName,
            fileName = fileName
        )

        file.bufferedWriter().use { writer ->
            writer.apply {
                appendLine("// Generated by KSP — do not edit")
                appendLine("package $PACKAGE.generated")
                appendLine()
                appendLine("import android.graphics.Bitmap")
                appendLine("import $PACKAGE.core.domain.transformation.*")
                appendLine("import $PACKAGE.feature.filters.data.model.*")
                appendLine("import $PACKAGE.core.filters.domain.model.*")
                appendLine()
                appendLine("internal fun mapFilter(filter: Filter<*>): Transformation<Bitmap> = filter.run {")
                appendLine("    when (this) {")

                annotated.forEach { filter ->
                    val filterName = filter.simpleName.asString()
                    val hasErrorCallback = filter.primaryConstructor
                        ?.parameters
                        ?.any { it.name?.asString() == "onError" }
                        ?: false
                    val constructorArgs = if (hasErrorCallback) {
                        "value, ::pushError"
                    } else {
                        "value"
                    }
                    val constructor = "$filterName($constructorArgs)"
                    appendLine("        is Filter.${filterName.removeSuffix("Filter")} -> $constructor")
                }

                appendLine()
                appendLine("        else -> throw IllegalArgumentException(\"No filter implementation for interface \${this::class.simpleName}\")")
                appendLine("    }")
                appendLine("}")
                appendLine()
                appendSerializationMappings(annotated)
            }
        }

        logger.info("FilterMappings generated successfully")

        return emptyList()
    }

    private fun Appendable.appendSerializationMappings(filters: List<KSClassDeclaration>) {
        appendLine("internal fun transformationFilterSerializationKey(filter: Filter<*>): String? = when (filter) {")
        filters.forEach { filter ->
            appendLine("    is ${filter.simpleName.asString()} -> \"${filter.qualifiedName!!.asString()}\"")
        }
        appendLine("    else -> null")
        appendLine("}")
        appendLine()
        appendLine("@Suppress(\"UNCHECKED_CAST\")")
        appendLine("internal fun createTransformationFilterFromKey(key: String, value: Any?): Filter<*>? = when (key) {")
        filters.forEach { filter ->
            val parameters = filter.primaryConstructor?.parameters.orEmpty()
            val valueParameter = parameters.firstOrNull { it.name?.asString() == "value" }
            val className = filter.simpleName.asString()
            val fallback = if (parameters.all { it.hasDefault }) "$className()" else "null"
            val constructor = if (valueParameter != null && parameters.all {
                    it == valueParameter || it.hasDefault
                }) {
                "if (value == null) $fallback else $className(value = value as ${
                    valueParameter.type.resolve().renderType()
                })"
            } else {
                fallback
            }
            appendLine("    \"${filter.qualifiedName!!.asString()}\" ->")
            appendLine("        runCatching { $constructor }.getOrElse { $fallback }")
        }
        appendLine("    else -> null")
        appendLine("}")
    }

    companion object {
        private const val PACKAGE = "com.t8rin.imagetoolbox"
    }
}